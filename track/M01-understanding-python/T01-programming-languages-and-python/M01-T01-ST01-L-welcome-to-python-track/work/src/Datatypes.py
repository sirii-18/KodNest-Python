#integers
a=10
print(type(a),a)

#floats
b=20.5
print(type(b),b)

#boolean
c=True
print(type(c),c)

#strings
d="Sirisha"
print(type(d),d)

#complex
e=10+20j
print(type(e),e)

#list
f=[1,2,3,4,5]
print(type(f),f)

#tuple
g=(1,2,3,4,5)
print(type(g),g)

#set
h={1,2,3,4,5}
print(type(h),h)

#dictionary
i={1:"Siri",2:"Blr",3:"KA"}
print(type(i),i)

#None
is_valid = None
print(type(is_valid),is_valid)

